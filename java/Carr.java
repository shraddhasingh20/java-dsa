public class Carr {
    String brand;
    int cost;

    // Constructor
    Carr(String brand, int cost) {
        this.brand = brand;
        this.cost = cost;
    }

    // Method to display details
    void display() {
        System.out.println("Brand: " + brand);
        System.out.println("Cost: " + cost);
    }
}
    
